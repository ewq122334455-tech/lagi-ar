#!/usr/bin/env node
/**
 * Turns the dist-offline build into a folder that works from file:// (double-click index.html), with no internet:
 *  - index.html: external font/preconnect links removed, the module script becomes a classic deferred script, no crossorigin
 *  - fonts: Pretendard copied next to the page (offline/fonts)
 *  - product data: public/products/**\/product.json + manifest.json are embedded and served by a tiny fetch() shim (browsers block
 *    fetch() of local files), so the shop works without a server
 * AI features (photo compositing, AI video, reviews, payments) need the internet and show their normal "could not connect" messages.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'dist-offline');
if (!fs.existsSync(path.join(out, 'index.html'))) throw new Error('run `vite build --config vite.offline.config.ts` first');

// 1) product data -> one script
const prodDir = path.join(root, 'public', 'products');
const manifest = JSON.parse(fs.readFileSync(path.join(prodDir, 'manifest.json'), 'utf8'));
const data = { 'products/manifest.json': manifest };
for (const id of manifest.products) data[`products/${id}/product.json`] = JSON.parse(fs.readFileSync(path.join(prodDir, id, 'product.json'), 'utf8'));
fs.writeFileSync(
  path.join(out, 'assets', 'offline-data.js'),
  `/* generated by scripts/make-offline.mjs */\nwindow.__LAGI_OFFLINE__ = ${JSON.stringify(data)};\n(function () {\n  var real = window.fetch ? window.fetch.bind(window) : null;\n  window.fetch = function (input, init) {\n    var url = typeof input === 'string' ? input : input && input.url ? input.url : '';\n    var key = url.split('?')[0].replace(/^.*?(products\\/.*)$/, '$1');\n    if (window.__LAGI_OFFLINE__[key]) return Promise.resolve(new Response(JSON.stringify(window.__LAGI_OFFLINE__[key]), { status: 200, headers: { 'Content-Type': 'application/json' } }));\n    // Real customer reviews live on the server: offline there are none (the page shows its example reviews).\n    if (/workers\\.dev\\/reviews/.test(url) && (!init || !init.method || init.method === 'GET')) return Promise.resolve(new Response(JSON.stringify({ reviews: [], total: 0, page: 1, pages: 1 }), { status: 200, headers: { 'Content-Type': 'application/json' } }));\n    return real ? real(input, init) : Promise.reject(new Error('offline'));\n  };\n})();\n`,
);

// 1b) the Adobe Fonts loader (bundled from the inline script in index.html) must not call the internet
const appFile = path.join(out, 'assets', 'app.js');
let app = fs.readFileSync(appFile, 'utf8');
const before = app.length;
app = app.replace(/`https:\/\/use\.typekit\.net\/\$\{[^}]+\}\.css`/g, '`data:text/css,`');
if (app.length === before) console.warn('warning: Adobe Fonts loader not found in app.js (already removed?)');
fs.writeFileSync(appFile, app);

// 2) fonts
fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'offline', 'fonts'))) fs.copyFileSync(path.join(root, 'offline', 'fonts', f), path.join(out, 'fonts', f));

// 3) index.html
let html = fs.readFileSync(path.join(out, 'index.html'), 'utf8');
html = html
  .replace(/<link rel="preconnect"[^>]*>\s*/g, '')
  .replace(/<script type="module">[\s\S]*?<\/script>\s*/g, '') // the Adobe Fonts loader
  .replace(/<link\s+rel="stylesheet"\s+href="https:\/\/cdn\.jsdelivr\.net[^>]*>\s*/g, '')
  .replace(/<noscript>[\s\S]*?<\/noscript>\s*/g, '')
  .replace(/<link rel="canonical"[^>]*>\s*/g, '')
  .replace(/ crossorigin(="[^"]*")?/g, '')
  .replace(/<script type="module"([^>]*) src="([^"]+)"([^>]*)><\/script>/g, '<script defer src="$2"></script>');
html = html.replace('</head>', '    <link rel="stylesheet" href="fonts/fonts.css" />\n    <script src="assets/offline-data.js"></script>\n  </head>');
fs.writeFileSync(path.join(out, 'index.html'), html);
console.log('offline site ready:', out);
